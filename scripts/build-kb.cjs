// Regenerates supabase/functions/_shared/knowledge/knowledgeBase.ts from the handbook Markdown files.
// Edge functions can't read loose .md files at runtime, so the handbooks ship as strings.
// Run after editing the Markdown:  node scripts/build-kb.cjs
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "supabase", "functions", "_shared", "knowledge");
const read = (f) => fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n");
const tax = read("taxpractice-kb.md");
const contract = read("contract-workspace-kb.md");
const out = `// GENERATED by scripts/build-kb.cjs from taxpractice-kb.md and contract-workspace-kb.md — edit the Markdown, then rerun.
export const TAXPRACTICE_KB = ${JSON.stringify(tax)};

export const CONTRACT_KB = ${JSON.stringify(contract)};

/** Handbooks plus the rules for using them, appended to the support-chat system prompt. */
export function knowledgeBlock(): string {
  return [
    "=== TAXPRACTICE APP SUPPORT HANDBOOK ===",
    "Higher View also runs TaxPractice, a training simulator for tax preparers. When a customer asks about TaxPractice (signing in, scenarios, the answer key, preparer links, Scan & organize, the Return checker, the Admin or Team page, or any TaxPractice error message), answer only from the handbook below. Quote exact on-screen messages and button names. If the handbook doesn't cover it, say so and offer to open a ticket.",
    "Rules: never ask for a password, real SSNs, or client documents (only the login email and office name). When the handbook says to escalate to the administrator (password resets, new logins, role or office changes, a scenario that won't save after retrying, a repeating page error, or anyone seeing another office's scenarios), call create_ticket with the details collected. Treat a report of seeing another office's scenarios as the highest priority.",
    "",
    TAXPRACTICE_KB,
    "",
    "=== CONTRACT WORKSPACE SUPPORT HANDBOOK ===",
    "Higher View also runs the Contract Workspace, where business owners brand or upload contracts and send signing links to their clients. When someone asks about it (the invitation email, the document password, Unlock, Customize Templates, My Contracts, Place fields, Sent Documents, signing links, countersigning, signed PDFs, or any Contract Workspace error message), answer only from the handbook below and follow its section 0 instructions. Use the exact button names. If the handbook doesn't cover it, say you're not sure and offer to open a ticket or connect them with an agent.",
    "Rules: never ask for, repeat, or guess a password, and never ask for card numbers. Support can't read a password back; a lost password or link, a missing invitation email, changing contracts or passwords, or a page that keeps failing means call create_ticket with the details collected. Wherever the handbook says \\"contact support\\", that means this chat: offer create_ticket or request_human_agent. Give no legal or tax advice about contract terms, and never promise a signed contract can be changed. Only discuss section 9 (Admin) if the person says they are Higher View staff.",
    "",
    CONTRACT_KB,
  ].join(${JSON.stringify("\n")});
}
`;
fs.writeFileSync(path.join(dir, "knowledgeBase.ts"), out);
console.log("wrote knowledgeBase.ts (" + (tax.length + contract.length) + " chars)");
