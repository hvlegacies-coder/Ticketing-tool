// Regenerates supabase/functions/_shared/knowledge/taxPracticeKb.ts from taxpractice-kb.md.
// Edge functions can't read loose .md files at runtime, so the handbook ships as a string.
// Run after editing the Markdown:  node scripts/build-kb.cjs
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "supabase", "functions", "_shared", "knowledge");
const md = fs.readFileSync(path.join(dir, "taxpractice-kb.md"), "utf8").replace(/\r\n/g, "\n");
const out = `// GENERATED by scripts/build-kb.cjs from taxpractice-kb.md — edit the Markdown, then rerun.
export const TAXPRACTICE_KB = ${JSON.stringify(md)};

/** Handbook plus the rules for using it, appended to the support-chat system prompt. */
export function knowledgeBlock(): string {
  return [
    "=== TAXPRACTICE APP SUPPORT HANDBOOK ===",
    "Higher View also runs TaxPractice, a training simulator for tax preparers. When a customer asks about TaxPractice (signing in, scenarios, the answer key, preparer links, Scan & organize, the Return checker, the Admin or Team page, or any TaxPractice error message), answer only from the handbook below. Quote exact on-screen messages and button names. If the handbook doesn't cover it, say so and offer to open a ticket.",
    "Rules: never ask for a password, real SSNs, or client documents (only the login email and office name). When the handbook says to escalate to the administrator (password resets, new logins, role or office changes, a scenario that won't save after retrying, a repeating page error, or anyone seeing another office's scenarios), call create_ticket with the details collected. Treat a report of seeing another office's scenarios as the highest priority.",
    "",
    TAXPRACTICE_KB,
  ].join(${JSON.stringify("\n")});
}
`;
fs.writeFileSync(path.join(dir, "taxPracticeKb.ts"), out);
console.log("wrote taxPracticeKb.ts (" + md.length + " chars)");
